-- ------------------------------------------------------------ updated_at triggers
CREATE OR REPLACE FUNCTION set_updated_at() RETURNS trigger AS $$
BEGIN
  NEW.updated_at = now();
  RETURN NEW;
END;
$$ LANGUAGE plpgsql;

CREATE TRIGGER wells_updated_at BEFORE UPDATE ON wells
  FOR EACH ROW EXECUTE FUNCTION set_updated_at();
CREATE TRIGGER products_updated_at BEFORE UPDATE ON products
  FOR EACH ROW EXECUTE FUNCTION set_updated_at();
CREATE TRIGGER inventory_updated_at BEFORE UPDATE ON inventory
  FOR EACH ROW EXECUTE FUNCTION set_updated_at();

-- ------------------------------------------------------------ views for common queries
CREATE VIEW v_core_2017 AS
SELECT s.id AS section_id, s.well_id, s.section_no, s.top_md, s.bottom_md,
       r.recovery, s.lithology, s.fluorescence, s.oil_show,
       o.structure_code, o.sedimentary_structure_code,
       o.fracture_desc, o.vug_desc, o.contact_relation_code,
       o.fossil_desc, o.dip_angle, o.gas_show_code, o.breakage_wear_code
FROM sections s
JOIN runs r ON r.id = s.run_id
LEFT JOIN core_observation o ON o.section_id = s.id;

CREATE VIEW v_core_fracture_stats AS
SELECT s.well_id, s.id AS section_id, s.section_no,
       count(f.id) AS fracture_count,
       avg(f.dip_angle) AS avg_dip,
       sum(f.length_mm) AS fracture_length
FROM sections s LEFT JOIN core_fracture f ON f.section_id = s.id
GROUP BY s.well_id, s.id, s.section_no;

CREATE VIEW v_core_vug_stats AS
SELECT s.well_id, s.id AS section_id, s.section_no,
       count(v.id) AS vug_count,
       sum(v.area_mm2) AS vug_area,
       avg(v.area_pct) AS avg_area_pct
FROM sections s LEFT JOIN core_vug v ON v.section_id = s.id
GROUP BY s.well_id, s.id, s.section_no;
