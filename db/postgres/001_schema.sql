-- ============================================================
-- Rock Core Database — PostgreSQL 16 + PostGIS + pgvector
-- Target schema v1.0
-- ============================================================

CREATE EXTENSION IF NOT EXISTS postgis;
CREATE EXTENSION IF NOT EXISTS vector;
CREATE EXTENSION IF NOT EXISTS pg_trgm;

-- ------------------------------------------------------------ dictionaries
CREATE TABLE dictionary (
  dict_type   text NOT NULL,
  code        text NOT NULL,
  name        text NOT NULL,
  parent_code text,
  sort_no     integer NOT NULL DEFAULT 0,
  remark      text,
  PRIMARY KEY (dict_type, code)
);

-- ------------------------------------------------------------ wells
CREATE TABLE wells (
  id          integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  code        text NOT NULL UNIQUE,
  name        text NOT NULL,
  region      text,
  tectonic    text,
  year        integer,
  type        text,
  lon         double precision,
  lat         double precision,
  kb          double precision,
  ground      double precision,
  final_depth double precision,
  inventory   numeric(12,2) DEFAULT 0,
  cuttings    integer DEFAULT 0,
  sidewall    integer DEFAULT 0,
  coverage    numeric(5,1) DEFAULT 0,
  scanned     numeric(10,2) DEFAULT 0,
  status      text,
  operator    text,
  updated_at  timestamptz DEFAULT now()
);
CREATE INDEX idx_wells_region ON wells(region);
CREATE INDEX idx_wells_tectonic ON wells(tectonic);
CREATE INDEX idx_wells_year ON wells(year);

-- spatial mirror; keep `wells` SELECT * safe for the existing API
CREATE TABLE well_geometry (
  well_id integer PRIMARY KEY REFERENCES wells(id) ON DELETE CASCADE,
  geom    geography(Point,4326) NOT NULL
);
CREATE INDEX idx_well_geometry_gist ON well_geometry USING gist(geom);

-- ------------------------------------------------------------ runs / strata / sections
CREATE TABLE runs (
  id          integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  well_id     integer NOT NULL REFERENCES wells(id) ON DELETE CASCADE,
  run_no      integer NOT NULL,
  top_md      double precision,
  bottom_md   double precision,
  footage     double precision,
  core_length double precision,
  recovery    double precision,
  layer       text,
  lithology   text,
  description text,
  drilled_at  timestamptz,
  UNIQUE (well_id, run_no)
);
CREATE INDEX idx_runs_well ON runs(well_id);

CREATE TABLE strata (
  id        integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  well_id   integer REFERENCES wells(id) ON DELETE CASCADE,
  run_id    integer REFERENCES runs(id) ON DELETE CASCADE,
  name      text,
  level     text,
  top_md    double precision,
  bottom_md double precision,
  color     text
);
CREATE INDEX idx_strata_well ON strata(well_id);
CREATE INDEX idx_strata_run ON strata(run_id);

CREATE TABLE sections (
  id          integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  run_id      integer REFERENCES runs(id) ON DELETE CASCADE,
  well_id     integer REFERENCES wells(id) ON DELETE CASCADE,
  section_no  text,
  top_md      double precision,
  bottom_md   double precision,
  length      double precision,
  box_no      text,
  slot        text,
  condition   text,
  oil_show    text,
  fluorescence text,
  rqd         double precision,
  lithology   text,
  color       text,
  pattern     text,
  description text,
  strip_file  text,
  strip_key   text,
  UNIQUE (run_id, section_no)
);
CREATE INDEX idx_sections_well ON sections(well_id);
CREATE INDEX idx_sections_run ON sections(run_id);
CREATE INDEX idx_sections_lith ON sections(lithology);

-- depth mirrors for range/GiST queries
CREATE TABLE run_depth (
  run_id integer PRIMARY KEY REFERENCES runs(id) ON DELETE CASCADE,
  depth  numrange NOT NULL
);
CREATE INDEX idx_run_depth_gist ON run_depth USING gist(depth);

CREATE TABLE section_depth (
  section_id integer PRIMARY KEY REFERENCES sections(id) ON DELETE CASCADE,
  depth      numrange NOT NULL
);
CREATE INDEX idx_section_depth_gist ON section_depth USING gist(depth);

-- ------------------------------------------------------------ images
