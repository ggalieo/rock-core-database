  device       text,
  operator     text,
  quality      text
);
CREATE INDEX idx_images_well ON images(well_id);
CREATE INDEX idx_images_run ON images(run_id);
CREATE INDEX idx_images_section ON images(section_id);
CREATE INDEX idx_images_type ON images(type);

CREATE TABLE image_depth (
  image_id integer PRIMARY KEY REFERENCES images(id) ON DELETE CASCADE,
  depth    numrange NOT NULL
);
CREATE INDEX idx_image_depth_gist ON image_depth USING gist(depth);

-- ------------------------------------------------------------ scans / products
CREATE TABLE scans (
